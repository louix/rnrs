// IR -> TS wrapper (hidden build output). Classes over the framework runtime
// (packages/rnr-runtime/src/runtime.ts); value types mirror the spec.

function tsType(t) {
  switch (t.k) {
    case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'string': return 'string';
    case 'bytes': return 'ArrayBuffer';
    case 'void': return 'void';
    case 'array': return `${wrapUnion(tsType(t.of))}[]`;
    case 'nullable': return `${tsType(t.of)} | null`;
    case 'record': case 'union': case 'native': return t.name;
    default: throw new Error(t.k);
  }
}
const wrapUnion = s => (s.includes('|') ? `(${s})` : s);

const hasNative = t => t.k === 'native' || (t.of !== undefined && hasNative(t.of));

/** JS argument value -> what the adapter receives (native wrappers -> handles). */
function toNative(t, expr) {
  if (!hasNative(t)) return expr;
  switch (t.k) {
    case 'native': return `handleOf(${expr})`;
    case 'array': return `(Array.isArray(${expr}) ? ${expr}.map((e: any) => ${toNative(t.of, 'e')}) : ${expr})`;
    case 'nullable': return `(${expr} === null ? null : ${toNative(t.of, expr)})`;
    default: return expr;
  }
}

/** Adapter result -> wrapper value (handles -> wrapper objects). */
function fromNative(t, expr) {
  if (!hasNative(t)) return expr;
  switch (t.k) {
    case 'native': return `new ${t.name}(this.host, ${expr} as object)`;
    case 'array': return `(${expr} as unknown[]).map(e => ${fromNative(t.of, 'e')})`;
    case 'nullable': return `(${expr} === null ? null : ${fromNative(t.of, expr)})`;
    default: return expr;
  }
}

function method(m, index, receiver) {
  const params = m.params.map(p => `${p.name}${p.optional ? '?' : ''}: ${tsType(p.type)}`);
  const args = `[${m.params.map(p => toNative(p.type, p.name)).join(', ')}]`;
  if (!m.async) {
    const ret = tsType(m.returns);
    // Up to four parameters: positional (host.callN, no argument array); more: one array.
    const call = m.params.length <= 4
      ? `this.host.call${m.params.length}(${[index, receiver, ...m.params.map(p => toNative(p.type, p.name))].join(', ')})`
      : `this.host.call(${index}, ${receiver}, ${args})`;
    const body = m.returns.k === 'void' ? `${call};` : `return ${hasNative(m.returns) ? fromNative(m.returns, call) : `${call} as ${ret}`};`;
    return `  ${m.name}(${params.join(', ')}): ${ret} {\n    ${body}\n  }`;
  }
  const ret = tsType(m.returns);
  const wrap = hasNative(m.returns) ? `, (value: unknown) => ${fromNative(m.returns, 'value')}` : '';
  params.push('options?: CallOptions');
  return `  ${m.name}(${params.join(', ')}): Promise<${ret}> {\n    return this.host.start(${index}, ${receiver}, ${args}, options${wrap}) as Promise<${ret}>;\n  }`;
}

function field(f) {
  return `${JSON.stringify(f.name)}${f.optional ? '?' : ''}: ${tsType(f.type)}`;
}

export function emitTs(ir, {runtimeImport, maxInFlight}) {
  const out = [`// @generated by tools/rnr-gen from ${ir.spec}; do not edit.\n// IR hash: ${ir.hash}`,
    `import {ModuleBase, NativeObjectBase, createModuleForTesting, handleOf, runtimeModule, type CallOptions} from '${runtimeImport}';`];
  for (const r of ir.records) out.push(`export interface ${r.name} {\n${r.fields.map(f => `  ${field(f)};`).join('\n')}\n}`);
  for (const u of ir.unions) {
    const variants = u.variants.map(v => {
      const members = [`${JSON.stringify(u.discriminator)}: ${JSON.stringify(v.tag)}`,
        ...v.literals.map(l => `${JSON.stringify(l.name)}: ${JSON.stringify(l.value)}`), ...v.fields.map(field)];
      return `  | {${members.join('; ')}}`;
    });
    out.push(`export type ${u.name} =\n${variants.join('\n')};`);
  }
  const indexed = ir.methods.map((m, i) => ({m, i}));
  for (const o of ir.objects) {
    const methods = indexed.filter(({m}) => m.owner === o.name).map(({m, i}) => method(m, i, 'this.handle'));
    out.push(`export class ${o.name} extends NativeObjectBase {\n${methods.join('\n\n')}\n}`);
  }
  const moduleMethods = indexed.filter(({m}) => !m.owner).map(({m, i}) => method(m, i, 'undefined'));
  out.push(`export class ${ir.module} extends ModuleBase {
  static readonly descriptor = {name: ${JSON.stringify(ir.module)}, hash: ${JSON.stringify(ir.hash)}, defaultMaxInFlight: ${maxInFlight}, protocol: 2};
${moduleMethods.length ? '\n' + moduleMethods.join('\n\n') + '\n' : ''}}`);
  const accessor = ir.module[0].toLowerCase() + ir.module.slice(1);
  out.push(`/** This runtime's framework-owned ${ir.module}: created on first use, torn down with the runtime. */
export function ${accessor}(): ${ir.module} {
  return runtimeModule(${ir.module});
}

/** Test hook: an extra adapter generation in this runtime; the caller tears it down. */
export function create${ir.module}ForTesting(maxInFlight: number): ${ir.module} {
  return createModuleForTesting(${ir.module}, maxInFlight);
}`);
  return out.join('\n\n') + '\n';
}
