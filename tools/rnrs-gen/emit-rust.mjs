// IR -> Rust: the public interface (committed in the author's crate) and the hidden glue
// (generic over rnrs_core::bind::Env, so one conversion implementation serves Android and
// the browser).

const KEYWORDS = new Set(
  (
    'as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref return ' +
    'self Self static struct super trait true type unsafe use where while async await dyn abstract become box do final macro override priv ' +
    'typeof unsized virtual yield try gen'
  ).split(' '),
);

export function snake(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .toLowerCase();
}

export function ident(name) {
  const s = snake(name);
  if (!/^[a-z_][a-z0-9_]*$/.test(s)) throw new Error(`${name} cannot be a Rust identifier`);
  return KEYWORDS.has(s) ? `r#${s}` : s;
}

const header = (ir, what) =>
  `// @generated by tools/rnrs-gen from ${ir.spec}; do not edit.\n// ${what}\n// IR hash: ${ir.hash}\n`;

// ---- Interface -------------------------------------------------------------------------

function interfaceType(t, owner) {
  switch (t.k) {
    case 'number':
      return 'f64';
    case 'boolean':
      return 'bool';
    case 'string':
      return 'String';
    case 'bytes':
      return 'Vec<u8>';
    case 'void':
      return '()';
    case 'array':
      return `Vec<${interfaceType(t.of, owner)}>`;
    case 'nullable':
      return `Option<${interfaceType(t.of, owner)}>`;
    case 'record':
    case 'union':
      return t.name;
    case 'native':
      return owner === t.name ? 'Native<Self>' : `Native<Self::${t.name}Impl>`;
    default:
      throw new Error(`no Rust type for ${t.k}`);
  }
}

function paramType(p, owner) {
  const t = interfaceType(p.type, owner);
  return p.optional ? `Option<${t}>` : t;
}

function traitMethods(methods, owner) {
  const out = [];
  for (const m of methods) {
    const params = m.params.map((p) => `${ident(p.name)}: ${paramType(p, owner)}`);
    const ret = `Result<${interfaceType(m.returns, owner)}, String>`;
    const name = ident(m.name);
    const doc = `    /// \`${m.name}(${m.params.map((p) => p.name + (p.optional ? '?' : '')).join(', ')})\`${m.async ? ' (async)' : ''}\n`;
    if (!m.async) {
      out.push(`${doc}    fn ${name}(&self${params.map((p) => ', ' + p).join('')}) -> ${ret};`);
      continue;
    }
    const refs = m.params.map((p) => `_${snake(p.name)}: &${paramType(p, owner)}`);
    out.push(
      `    /// Runs on the JS thread before admission: an error rejects the call without starting\n` +
        `    /// work. Default: accept.\n` +
        `    fn validate_${snake(m.name)}(&self${refs.map((p) => ', ' + p).join('')}) -> Result<(), String> {\n        Ok(())\n    }`,
    );
    out.push(
      `${doc}    /// The future runs on the module's executor (\`Send\` natively, browser-local on Wasm).\n` +
        `    /// \`cancel\` is the operation's cooperative cancellation signal.\n` +
        `    fn ${name}(&self${params.map((p) => ', ' + p).join('')}, cancel: CancelToken) -> impl Future<Output = ${ret}> + MaybeSend;`,
    );
  }
  return out.join('\n\n');
}

/** `core`: the path of rnrs-core in the module crate (`rnrs_core`, `rnrs::core`, or a renamed
 *  dependency's identifier; see interfaceCore in cli.mjs). */
export function emitInterface(ir, { core = 'rnrs_core' } = {}) {
  const parts = [
    header(ir, 'Public Rust interface of the module: implement these traits.'),
    '#![allow(dead_code)]\n',
    `#[allow(unused_imports)]\nuse std::future::Future;\n\n#[allow(unused_imports)]\nuse ${core}::bind::{MaybeSend, NativeObject};\n#[allow(unused_imports)]\nuse ${core}::{CancelToken, Native};\n`,
  ];
  for (const r of ir.records) {
    parts.push(
      `/// Record \`${r.name}\`: converted field by field, by value.\n#[derive(Debug, Clone, PartialEq)]\npub struct ${r.name} {\n${r.fields
        .map(
          (f) =>
            `    pub ${ident(f.name)}: ${f.optional ? `Option<${interfaceType(f.type)}>` : interfaceType(f.type)},`,
        )
        .join('\n')}\n}\n`,
    );
  }
  for (const u of ir.unions) {
    const variants = u.variants.map((v) => {
      const lits = v.literals.length
        ? ` (also ${v.literals.map((l) => `${l.name}: ${JSON.stringify(l.value)}`).join(', ')})`
        : '';
      const doc = `    /// \`${u.discriminator}: ${JSON.stringify(v.tag)}\`${lits}`;
      if (!v.fields.length) return `${doc}\n    ${v.rustName},`;
      return `${doc}\n    ${v.rustName} {\n${v.fields.map((f) => `        ${ident(f.name)}: ${f.optional ? `Option<${interfaceType(f.type)}>` : interfaceType(f.type)},`).join('\n')}\n    },`;
    });
    parts.push(
      `/// Discriminated union \`${u.name}\` (discriminator \`${u.discriminator}\`).\n#[derive(Debug, Clone, PartialEq)]\npub enum ${u.name} {\n${variants.join('\n')}\n}\n`,
    );
  }
  for (const o of ir.objects) {
    const methods = ir.methods.filter((m) => m.owner === o.name);
    parts.push(
      `/// Native object \`${o.name}\`. JS wrappers, in-flight operations and other owners hold\n/// \`Native\` clones; the object is dropped with its last owner.\npub trait ${o.name}: NativeObject {\n${traitMethods(methods, o.name)}\n}\n`,
    );
  }
  const moduleMethods = ir.methods.filter((m) => !m.owner);
  const assoc = ir.objects.map((o) => `    type ${o.name}Impl: ${o.name};`).join('\n');
  parts.push(
    `/// Module \`${ir.module}\`: one instance per JS runtime (adapter generation), created with\n/// \`Default\`.\npub trait ${ir.module}: NativeObject + Default {\n${assoc}${assoc && moduleMethods.length ? '\n\n' : ''}${traitMethods(moduleMethods, null)}\n}\n`,
  );
  return parts.join('\n');
}

// ---- Glue --------------------------------------------------------------------------------

function glueType(t) {
  switch (t.k) {
    case 'number':
      return 'f64';
    case 'boolean':
      return 'bool';
    case 'string':
      return 'String';
    case 'bytes':
      return 'Vec<u8>';
    case 'void':
      return '()';
    case 'array':
      return `Vec<${glueType(t.of)}>`;
    case 'nullable':
      return `Option<${glueType(t.of)}>`;
    case 'record':
    case 'union':
      return `spec::${t.name}`;
    case 'native':
      return `Native<${t.name}Impl>`;
    default:
      throw new Error(t.k);
  }
}

/** Expression converting JS value `v` at `path` (all `&mut dyn Env` named `env`). */
function readExpr(t, v, path) {
  switch (t.k) {
    case 'number':
    case 'boolean':
    case 'string':
      return `<${glueType(t)} as FromJs>::from_js(env, ${v}, ${path})`;
    case 'bytes':
      return `bytes_from_js(env, ${v}, ${path})`;
    case 'record':
    case 'union':
      return `from_js_${snake(t.name)}(env, ${v}, ${path})`;
    case 'native':
      return `native_from_js::<${t.name}Impl>(env, ${v}, ${path}, ${JSON.stringify(t.name)})`;
    case 'array':
      return `array_from_js_with(env, ${v}, ${path}, &mut |env, v, path| ${readExpr(t.of, 'v', 'path')})`;
    case 'nullable':
      return `nullable_from_js_with(env, ${v}, ${path}, &mut |env, v, path| ${readExpr(t.of, 'v', 'path')})`;
    default:
      throw new Error(t.k);
  }
}

/** Expression converting owned Rust value `value` to a JS value. */
function writeExpr(t, value) {
  switch (t.k) {
    case 'number':
    case 'boolean':
    case 'string':
    case 'void':
      return `IntoJs::into_js(${value}, env)`;
    case 'bytes':
      return `bytes_into_js(${value}, env)`;
    case 'record':
    case 'union':
      return `into_js_${snake(t.name)}(${value}, env)`;
    case 'native':
      return `native_into_js(env, ${value}, ${JSON.stringify(t.name)})`;
    case 'array':
      return `array_into_js_with(${value}, env, &mut |value, env| ${writeExpr(t.of, 'value')})`;
    case 'nullable':
      return `nullable_into_js_with(${value}, env, &mut |value, env| ${writeExpr(t.of, 'value')})`;
    default:
      throw new Error(t.k);
  }
}

function readField(f, objectVar, pathVar) {
  const key = JSON.stringify(f.name);
  const fieldPath = `&${pathVar}.field(${key})`;
  return f.optional
    ? `{ let field = env.get_property(${objectVar}, ${key})?; optional_with(env, field, ${fieldPath}, &mut |env, v, path| ${readExpr(f.type, 'v', 'path')})? }`
    : `{ let field = env.get_property(${objectVar}, ${key})?; ${readExpr(f.type, 'field', fieldPath)}? }`;
}

function writeFields(fields, objectVar, access) {
  return fields
    .map((f) => {
      const key = JSON.stringify(f.name);
      const src = access(f);
      if (f.optional)
        return `    if let Some(value) = ${src} {\n        let value = ${writeExpr(f.type, 'value')}?;\n        env.set_property(${objectVar}, ${key}, value)?;\n    }`;
      return `    let value = ${writeExpr(f.type, src)}?;\n    env.set_property(${objectVar}, ${key}, value)?;`;
    })
    .join('\n');
}

function recordGlue(r) {
  const s = snake(r.name);
  const fields = r.fields
    .map((f) => `        ${ident(f.name)}: ${readField(f, 'v', 'path')},`)
    .join('\n');
  return `#[allow(dead_code)]
fn from_js_${s}(env: &mut dyn Env, v: Val, path: &Path<'_>) -> Result<spec::${r.name}, BindError> {
    expect_record(env, v, path, ${JSON.stringify(r.name)})?;
    // Fields are read in declaration order; other properties are ignored.
    Ok(spec::${r.name} {
${fields}
    })
}

#[allow(unused_variables, dead_code)]
fn into_js_${s}(record: spec::${r.name}, env: &mut dyn Env) -> Result<Val, BindError> {
    let object = env.object();
${writeFields(r.fields, 'object', (f) => `record.${ident(f.name)}`)}
    Ok(object)
}
`;
}

function unionGlue(u) {
  const s = snake(u.name);
  const disc = JSON.stringify(u.discriminator);
  const expectedTags = u.variants.map((v) => JSON.stringify(v.tag)).join(', ');
  const readArms = u.variants
    .map((v) => {
      const lits = v.literals
        .map(
          (l) =>
            `            expect_literal(env, v, ${JSON.stringify(l.name)}, ${JSON.stringify(l.value)}, path)?;\n`,
        )
        .join('');
      const body = v.fields.length
        ? `spec::${u.name}::${v.rustName} {\n${v.fields.map((f) => `                ${ident(f.name)}: ${readField(f, 'v', 'path')},`).join('\n')}\n            }`
        : `spec::${u.name}::${v.rustName}`;
      return `        Some(${JSON.stringify(v.tag)}) => {\n${lits}            Ok(${body})\n        }`;
    })
    .join('\n');
  const writeArms = u.variants
    .map((v) => {
      // Fields bind to prefixed locals so names like `object` or `value` cannot shadow glue locals.
      const bind = v.fields.length
        ? ` { ${v.fields.map((f) => `${ident(f.name)}: field_${snake(f.name)}`).join(', ')} }`
        : '';
      const lits = [[u.discriminator, v.tag], ...v.literals.map((l) => [l.name, l.value])]
        .map(
          ([k, val]) =>
            `            let value = env.string(${JSON.stringify(val)});\n            env.set_property(object, ${JSON.stringify(k)}, value)?;`,
        )
        .join('\n');
      const fields = writeFields(v.fields, 'object', (f) => `field_${snake(f.name)}`)
        .split('\n')
        .map((l) => '        ' + l)
        .join('\n');
      return `        spec::${u.name}::${v.rustName}${bind} => {\n${lits}\n${v.fields.length ? fields + '\n' : ''}        }`;
    })
    .join('\n');
  return `#[allow(dead_code)]
fn from_js_${s}(env: &mut dyn Env, v: Val, path: &Path<'_>) -> Result<spec::${u.name}, BindError> {
    expect_record(env, v, path, ${JSON.stringify(u.name)})?;
    let tag = tag_of(env, v, ${disc})?;
    match tag.as_deref() {
${readArms}
        Some(other) => Err(BindError::type_error(format!("{}: unknown ${u.name} tag {other:?}; expected one of ${expectedTags.replace(/"/g, '\\"')}", path.field(${disc})))),
        None => Err(BindError::type_error(format!("{} must be one of ${expectedTags.replace(/"/g, '\\"')}", path.field(${disc})))),
    }
}

#[allow(unused_variables, dead_code)]
fn into_js_${s}(value: spec::${u.name}, env: &mut dyn Env) -> Result<Val, BindError> {
    let object = env.object();
    match value {
${writeArms}
    }
    Ok(object)
}
`;
}

function readArg(p, i) {
  const name = JSON.stringify(p.name);
  const read = readExpr(p.type, 'v', `&Path::root(${name})`);
  return p.optional
    ? `        let arg_${snake(p.name)} = { let env = &mut *cx.env; let v = arg_val(env, args, ${i}); optional_with(env, v, &Path::root(${name}), &mut |env, v, _| ${read})? };`
    : `        let arg_${snake(p.name)} = { let env = &mut *cx.env; let v = arg_val(env, args, ${i}); ${read}? };`;
}

function callArm(m, index) {
  const lines = [`        // ${m.owner ? m.owner + '.' : ''}${m.name}${m.async ? ' (async)' : ''}`];
  // Arguments first (they may run JS getters), then the receiver as an owned clone.
  m.params.forEach((p, i) => lines.push(readArg(p, i)));
  // Conversion may have run JS that tore the adapter down: no method runs on a closed one.
  if (m.params.length) lines.push(`        cx.check_open()?;`);
  if (m.owner)
    lines.push(
      `        let receiver: Native<${m.owner}Impl> = native_from_js(cx.env, this, &Path::root("this"), ${JSON.stringify(m.owner)})?;`,
    );
  else lines.push(`        let receiver: Native<Module> = cx.instance::<Module>().clone();`);
  // Argument locals are prefixed so parameter names cannot shadow glue locals (env, receiver, ...).
  const argList = m.params.map((p) => `arg_${snake(p.name)}`).join(', ');
  if (!m.async) {
    lines.push(
      `        let result = receiver.${ident(m.name)}(${argList}).map_err(BindError::error)?;`,
    );
    lines.push(`        let env = &mut *cx.env;`);
    lines.push(`        ${writeExpr(m.returns, 'result')}`);
  } else {
    const refs = m.params.map((p) => `&arg_${snake(p.name)}`).join(', ');
    lines.push(
      `        receiver.validate_${snake(m.name)}(${refs}).map_err(BindError::range_error)?;`,
    );
    lines.push(`        cx.start(move |cancel| async move {`);
    lines.push(
      `            let result = receiver.${ident(m.name)}(${argList}${argList ? ', ' : ''}cancel).await?;`,
    );
    lines.push(
      `            Ok(pending(move |env: &mut dyn Env| ${writeExpr(m.returns, 'result')}))`,
    );
    lines.push(`        })`);
  }
  return `    ${index} => {\n${lines.join('\n')}\n    }`;
}

export function emitGlue(ir, { crate, moduleType }) {
  const traits = [ir.module, ...ir.objects.map((o) => o.name)]
    .map((n) => `spec::${n} as _`)
    .join(', ');
  const aliases = ir.objects
    .map((o) => `type ${o.name}Impl = <Module as spec::${ir.module}>::${o.name}Impl;`)
    .join('\n');
  const methods = ir.methods
    .map(
      (m) =>
        `    MethodDef { name: ${JSON.stringify((m.owner ? m.owner + '.' : '') + m.name)}, kind: MethodKind::${m.async ? 'Async' : 'Sync'} },`,
    )
    .join('\n');
  const natives = ir.objects
    .map(
      (o) =>
        `    NativeTypeDef { spec_name: ${JSON.stringify(o.name)}, rust_type: std::any::type_name::<${o.name}Impl> },`,
    )
    .join('\n');
  return `${header(ir, 'Hidden binding glue (build output). Generic over rnrs_core::bind::Env.')}
#[allow(unused_imports)]
use rnrs_core::bind::*;
#[allow(unused_imports)]
use rnrs_core::Native;
use ${crate}::rnrs_interface as spec;
#[allow(unused_imports)]
use {${traits}};

type Module = ${crate}::${moduleType};
${aliases}

pub static MODULE: ModuleDef = ModuleDef {
    name: ${JSON.stringify(ir.module)},
    hash: ${JSON.stringify(ir.hash)},
    methods: &[
${methods}
    ],
    native_types: &[
${natives}
    ],
    instantiate: || Ok(Box::new(Native::new(Module::default()))),
    call,
};

#[allow(unused_variables, clippy::let_unit_value)]
fn call(cx: &mut Call<'_>, method: u32, this: Val, args: &[Val]) -> Result<Val, BindError> {
    match method {
${ir.methods.map(callArm).join('\n')}
    _ => Err(BindError::range_error(format!("${ir.module}: no method #{method}"))),
    }
}

${ir.records.map(recordGlue).join('\n')}
${ir.unions.map(unionGlue).join('\n')}`;
}
